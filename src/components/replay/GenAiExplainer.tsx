'use client';

/**
 * src/components/replay/GenAiExplainer.tsx
 * GenAI Personalized Recommendation & Explanation Component.
 * Grounded STRICTLY in engine telemetry with deterministic number validation.
 * Supports Household, Hostel, and Facility operator profiles.
 */

import React, { useState, useEffect } from 'react';
import type { Item } from '@/domain/types';
import type { ItemDecision } from '@/engine';
import { appendAuditEvent, createAuditEvent } from '@/engine/audit';
import type { UserProfile, EngineExplanationInput } from '@/lib/ai/explainTemplates';
import { getTemplateExplanation, getBatchSummaryExplanation } from '@/lib/ai/explainTemplates';

interface GenAiExplainerProps {
  items: Item[];
  decisions: ItemDecision[];
  threshold?: number;
  className?: string;
}

export function GenAiExplainer({
  items,
  decisions,
  threshold = 0.30,
  className = '',
}: GenAiExplainerProps) {
  const [profile, setProfile] = useState<UserProfile>('household');
  const [selectedItemId, setSelectedItemId] = useState<string>('batch');
  const [explanation, setExplanation] = useState<string>('');
  const [source, setSource] = useState<'template' | 'ai'>('template');
  const [provider, setProvider] = useState<string | undefined>();
  const [loading, setLoading] = useState<boolean>(false);
  const [notice, setNotice] = useState<string | null>(null);

  // Auto-generate deterministic explanation whenever inputs change
  useEffect(() => {
    handleGenerate(true);
  }, [selectedItemId, profile, items, decisions]);

  const handleGenerate = async (fallbackOnly = false) => {
    setNotice(null);

    // 1. Batch mode
    if (selectedItemId === 'batch') {
      const hazardCount = decisions.filter((d) => d.route === 'hazard_hold' || d.route === 'inspection_line').length;
      const diversionRate = items.length > 0 ? ((items.length - hazardCount) / items.length) * 100 : 0;
      const text = getBatchSummaryExplanation(items.length, hazardCount, diversionRate, profile);
      setExplanation(text);
      setSource('template');
      setProvider(undefined);

      appendAuditEvent(
        createAuditEvent({
          itemId: null,
          itemName: 'BATCH_SUMMARY',
          action: 'EXPLANATION_GENERATED',
          reasonCode: 'POLICY_CHANGE',
          fromRoute: null,
          toRoute: null,
          provenance: 'Human-verified',
          notes: `profile=${profile}, source=Template`,
        })
      );
      return;
    }

    // 2. Single item mode
    const item = items.find((i) => i.id === selectedItemId);
    const decision = decisions.find((d) => d.itemId === selectedItemId);

    if (!item || !decision) {
      setExplanation('Item decision telemetry not available.');
      return;
    }

    const payload: EngineExplanationInput = {
      item: {
        id: item.id,
        name: item.name,
        primaryClass: item.primaryClass,
        hazardProbability: item.hazardProbability,
        confidence: item.overallConfidence ?? 0.85,
      },
      decision: {
        route: decision.route,
        gateScore: decision.gateScore,
        threshold,
        floorTriggered: decision.safetyFloorTriggered,
      },
      profile,
    };

    // Default template calculation
    const templateText = getTemplateExplanation(payload);

    if (fallbackOnly) {
      setExplanation(templateText);
      setSource('template');
      setProvider(undefined);
      return;
    }

    // Attempt AI provider chain via server API
    setLoading(true);
    try {
      const res = await fetch('/api/explain', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(payload),
      });

      if (!res.ok) {
        setNotice('AI providers busy, showing template explanation');
        setExplanation(templateText);
        setSource('template');
        setProvider(undefined);
      } else {
        const data = await res.json();
        setExplanation(data.explanation || templateText);
        setSource(data.source === 'ai' ? 'ai' : 'template');
        setProvider(data.provider);

        appendAuditEvent(
          createAuditEvent({
            itemId: item.id,
            itemName: item.name,
            action: 'EXPLANATION_GENERATED',
            reasonCode: 'POLICY_CHANGE',
            fromRoute: null,
            toRoute: null,
            provenance: 'Human-verified',
            notes: data.source === 'ai' ? `AI-generated by ${data.provider}` : 'Template',
          })
        );
      }
    } catch {
      setNotice('Network unavailable, showing template explanation');
      setExplanation(templateText);
      setSource('template');
      setProvider(undefined);
    } finally {
      setLoading(false);
    }
  };

  return (
    <div
      className={`border border-border-subtle bg-[#080b0f] p-4 rounded-[2px] space-y-4 ${className}`}
      aria-labelledby="genai-explainer-heading"
    >
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-2 border-b border-border-subtle pb-3">
        <div className="space-y-0.5">
          <div className="text-[10px] font-mono uppercase tracking-widest text-amber-500 font-bold">
            PS06 Generative AI // Personalized Recommendations
          </div>
          <h3 id="genai-explainer-heading" className="text-base font-display font-bold text-text-primary">
            Sorting Recommendation &amp; Gate Explanation
          </h3>
        </div>

        {/* Profile Selector */}
        <div className="flex items-center gap-1 bg-bg-surface border border-border-subtle p-0.5 rounded-[2px]">
          {(
            [
              ['household', 'Household'],
              ['hostel', 'Hostel'],
              ['facility_operator', 'Facility Operator'],
            ] as const
          ).map(([key, label]) => (
            <button
              key={key}
              type="button"
              onClick={() => setProfile(key)}
              className={`px-2.5 py-1 text-[11px] font-mono transition-colors rounded-[2px] ${
                profile === key
                  ? 'bg-amber-500 text-black font-bold'
                  : 'text-text-muted hover:text-text-primary'
              }`}
              aria-pressed={profile === key}
            >
              {label}
            </button>
          ))}
        </div>
      </div>

      {/* Target Item Selector & Action */}
      <div className="flex flex-wrap items-center justify-between gap-3 text-xs font-mono">
        <div className="flex items-center gap-2">
          <label htmlFor="explain-item-select" className="text-text-muted">
            Target Item:
          </label>
          <select
            id="explain-item-select"
            value={selectedItemId}
            onChange={(e) => setSelectedItemId(e.target.value)}
            className="bg-bg-surface border border-border-default text-text-primary px-2.5 py-1 rounded-[2px] text-xs font-mono focus-visible:outline-2 focus-visible:outline-amber-500"
          >
            <option value="batch">-- Batch Stream Summary --</option>
            {items.map((it) => (
              <option key={it.id} value={it.id}>
                {it.id}: {it.name.slice(0, 24)} ({it.primaryClass})
              </option>
            ))}
          </select>
        </div>

        <button
          type="button"
          onClick={() => handleGenerate(false)}
          disabled={loading}
          className="px-3 py-1 bg-amber-500/15 hover:bg-amber-500/25 border border-amber-500/40 text-amber-300 disabled:opacity-40 text-xs font-mono font-bold rounded-[2px] transition-colors"
        >
          {loading ? 'Consulting Engine & AI...' : 'Request AI Analysis'}
        </button>
      </div>

      {/* Output Display Box */}
      <div className="bg-[#0b1017] border border-border-subtle p-3.5 rounded-[2px] space-y-2">
        <div className="flex items-center justify-between text-[11px] font-mono border-b border-slate-800 pb-1.5">
          <span className="text-text-muted">
            Explanation source:{' '}
            <span className={source === 'ai' ? 'text-emerald-400 font-bold' : 'text-sky-400 font-bold'}>
              {source === 'ai'
                ? `AI-generated by ${provider || 'configured provider'}`
                : 'Template explanation (Calculated)'}
            </span>
          </span>
          <span className="text-text-muted uppercase">Profile: {profile.replace('_', ' ')}</span>
        </div>

        <p className="text-xs sm:text-sm font-sans text-text-primary leading-relaxed">
          {explanation}
        </p>

        {notice && (
          <div className="text-[11px] font-mono text-amber-400/90 pt-1 border-t border-slate-800">
            &bull; {notice}
          </div>
        )}
      </div>

      <div className="text-[10px] font-mono text-text-muted leading-tight">
        Grounding invariant: LLM output is passed through a deterministic validator that extracts all numbers and verifies them against the engine input before rendering.
      </div>
    </div>
  );
}
